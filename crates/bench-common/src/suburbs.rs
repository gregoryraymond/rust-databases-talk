#[derive(Debug, Clone, Copy)]
pub struct Suburb {
    pub name: &'static str,
    pub outline: &'static [(f64, f64)],
}

impl Suburb {
    pub fn outline_wkt(&self) -> String {
        let points: Vec<String> = self
            .outline
            .iter()
            .map(|(lon, lat)| format!("{lon} {lat}"))
            .collect();
        format!("POLYGON(({}))", points.join(", "))
    }
}

