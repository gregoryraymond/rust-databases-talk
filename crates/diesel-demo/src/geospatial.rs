//! The geospatial demo through Diesel on PostGIS, with `postgis_diesel` mapping geometry to Rust types.

use anyhow::{Context as _, Result};
use bench_common::{
    database::postgres_url,
    geo_workload::{MOVE_TO, SEARCH_POINT, SEARCH_RADIUS_METRES, WGS84_SRID},
    places::Suburb,
    postgis::SETUP,
    report::{GeoReport, Nearby, describe_school},
    sample_data::{SCHOOLS, SUBURBS},
};
use chrono::{DateTime, Utc};
use diesel::{pg::PgConnection, prelude::*};
use postgis_diesel::{
    functions::{st_contains, st_d_within},
    types::{Point, Polygon},
};
use uuid::Uuid;

/// PostGIS functions `postgis_diesel` does not ship, declared so queries using them type-check.
mod sql {
    use diesel::sql_types::Double;
    use postgis_diesel::sql_types::{Geography, Geometry};

    diesel::define_sql_function! {
        /// Casts a geometry to geography, so distances come out in metres on the spheroid.
        #[sql_name = "geography"]
        fn to_geography(geometry: Geometry) -> Geography;
    }

    diesel::define_sql_function! {
        /// Distance in metres between two geographies.
        #[sql_name = "ST_Distance"]
        fn st_distance(left: Geography, right: Geography) -> Double;
    }
}

use diesel_demo::{
    models::{NewSchool, SchoolRow, point},
    schema::{school, suburb},
};

/// A new suburb row. `center` is generated by Postgres, so it is not here.
#[derive(Insertable)]
#[diesel(table_name = suburb)]
struct NewSuburb<'a> {
    /// A time-ordered id.
    id: Uuid,
    /// The locality name.
    name: &'a str,
    /// The state it is in.
    state: &'a str,
    /// The boundary.
    outline: Polygon<Point>,
    /// When the row was made.
    created_at: DateTime<Utc>,
}

/// The columns a move changes: a separate struct from the insert, as Diesel updates need.
#[derive(AsChangeset)]
#[diesel(table_name = school)]
struct MoveSchool {
    /// The new location.
    location: Point,
    /// When it moved.
    updated_at: DateTime<Utc>,
}

/// A suburb's outline as a WGS 84 polygon.
fn outline(suburb: &Suburb) -> Result<Polygon<Point>> {
    let mut polygon = Polygon::new(Some(WGS84_SRID));
    polygon
        .add_points(suburb.outline.iter().copied().map(point))
        .context("building the outline")?;
    Ok(polygon)
}

/// Creates, reads, searches, moves and deletes the sample suburbs and schools on PostGIS.
pub fn run() -> Result<GeoReport> {
    let mut conn = PgConnection::establish(&postgres_url()).context("connecting to Postgres")?;
    for sql in SETUP {
        diesel::sql_query(*sql)
            .execute(&mut conn)
            .with_context(|| format!("running {sql}"))?;
    }

    let first = insert_samples(&mut conn)?;

    let row: SchoolRow = school::table
        .find(first)
        .select(SchoolRow::as_select())
        .first(&mut conn)
        .context("reading the school back")?;

    let search = point(SEARCH_POINT);
    let suburbs_at_search_point = suburb::table
        .filter(st_contains(suburb::outline, search))
        .select(suburb::name)
        .order(suburb::name)
        .load(&mut conn)
        .context("finding the suburb at the search point")?;

    let distance = sql::st_distance(
        sql::to_geography(school::location),
        sql::to_geography(search),
    );
    let nearby: Vec<(String, f64)> = school::table
        .filter(st_d_within(
            sql::to_geography(school::location),
            sql::to_geography(search),
            SEARCH_RADIUS_METRES,
        ))
        .select((school::name, distance))
        .order(distance)
        .load(&mut conn)
        .context("finding nearby schools")?;

    diesel::update(school::table.find(first))
        .set(MoveSchool {
            location: point(MOVE_TO),
            updated_at: Utc::now(),
        })
        .execute(&mut conn)
        .context("moving the school")?;
    let suburb_after_move = school::table
        .inner_join(suburb::table.on(st_contains(suburb::outline, school::location)))
        .filter(school::id.eq(first))
        .select(suburb::name)
        .first(&mut conn)
        .optional()
        .context("finding the school's new suburb")?;

    diesel::delete(school::table.find(first))
        .execute(&mut conn)
        .context("deleting the school")?;
    let schools_after_delete = school::table
        .count()
        .get_result(&mut conn)
        .context("counting schools")?;

    Ok(GeoReport {
        library: "diesel",
        engine: "postgis",
        suburbs: SUBURBS.len(),
        schools: SCHOOLS.len(),
        read_back: describe_school(
            row.id,
            &row.name,
            row.location.x,
            row.location.y,
            row.created_at,
        ),
        suburbs_at_search_point,
        nearby: nearby
            .into_iter()
            .map(|(name, metres)| Nearby { name, metres })
            .collect(),
        suburb_after_move,
        schools_after_delete,
    })
}

/// Inserts the sample suburbs and schools, returning the first school's id.
fn insert_samples(conn: &mut PgConnection) -> Result<Uuid> {
    let now = Utc::now();
    let suburbs = SUBURBS
        .iter()
        .map(|s| {
            Ok(NewSuburb {
                id: Uuid::now_v7(),
                name: s.name,
                state: s.state,
                outline: outline(s)?,
                created_at: now,
            })
        })
        .collect::<Result<Vec<_>>>()?;
    diesel::insert_into(suburb::table)
        .values(&suburbs)
        .execute(conn)
        .context("inserting suburbs")?;

    let schools: Vec<NewSchool> = SCHOOLS
        .iter()
        .map(|s| NewSchool {
            id: Uuid::now_v7(),
            name: s.name,
            sector: s.sector,
            school_type: s.school_type,
            location: point((s.lon, s.lat)),
            created_at: now,
            updated_at: now,
        })
        .collect();
    diesel::insert_into(school::table)
        .values(&schools)
        .execute(conn)
        .context("inserting schools")?;
    Ok(schools.first().context("there are no sample schools")?.id)
}
